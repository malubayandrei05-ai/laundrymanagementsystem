CREATE DATABASE IF NOT EXISTS laundriflow CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE laundriflow;
CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY, full_name VARCHAR(140) NOT NULL, username VARCHAR(80) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role ENUM('admin','customer','staff') NOT NULL DEFAULT 'customer', active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS products (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(140) NOT NULL, price DECIMAL(10,2) NOT NULL DEFAULT 0,
 stock DECIMAL(10,2) NOT NULL DEFAULT 0, unit VARCHAR(24) NOT NULL DEFAULT 'pcs', updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS orders (
 id INT AUTO_INCREMENT PRIMARY KEY, order_code VARCHAR(30) UNIQUE NOT NULL, customer_id INT NOT NULL,
 service VARCHAR(120) NOT NULL, weight DECIMAL(8,2) NOT NULL, amount DECIMAL(10,2) NOT NULL,
 paid DECIMAL(10,2) NOT NULL DEFAULT 0, status VARCHAR(40) NOT NULL DEFAULT 'Received', fulfillment ENUM('Pickup','Delivery') NOT NULL DEFAULT 'Pickup',
 staff_name VARCHAR(140) NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(customer_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS staff_duty (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(140) NOT NULL UNIQUE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
